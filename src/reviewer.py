import json
from pathlib import Path

import boto3
import re
from src.document_parser import extract_pdf_text
from src.document_normalizer import normalize_document
from src.deterministic_rules import (
    check_rule_10,
    check_rule_13,
    check_rule_19,
    check_rule_20,
    check_rule_23,
    check_rule_25,
)

# ============================================================
# CONFIGURATION
# ============================================================

REGION = "us-east-1"
KNOWLEDGE_BASE_ID = "DJ33HADJNL"
#MODEL_ID = "meta.llama3-8b-instruct-v1:0"
MODEL_ID = "amazon.nova-pro-v1:0"

INPUT_DIR = Path("data/test_proposals")
OUTPUT_DIR = Path("data/results")
PROMPT_PATH = Path("prompts/reviewer_prompt.txt")


# ============================================================
# AWS CLIENTS
# ============================================================

kb_client = boto3.client(
    "bedrock-agent-runtime",
    region_name=REGION,
)

bedrock_client = boto3.client(
    "bedrock-runtime",
    region_name=REGION,
)


# ============================================================
# LOAD PROPOSAL
# ============================================================
def load_proposal(file_path: Path) -> str:
    if file_path.suffix.lower() == ".pdf":
        return extract_pdf_text(file_path)

    if file_path.suffix.lower() == ".txt":
        return file_path.read_text(encoding="utf-8")

    raise ValueError(f"Unsupported file format: {file_path.suffix}")

# ============================================================
# RETRIEVAL
# ============================================================

def retrieve_rules(query: str) -> str:
    """
    Retrieve relevant quality rules from the Bedrock Knowledge Base.

    Returns the retrieved chunks combined into a single text context.
    """

    response = kb_client.retrieve(
        knowledgeBaseId=KNOWLEDGE_BASE_ID,
        retrievalQuery={
            "text": query
        },
        retrievalConfiguration={
            "managedSearchConfiguration": {
                "numberOfResults": 5
            }
        },
    )

    retrieved_results = response["retrievalResults"]

    context = "\n\n".join(
        result["content"]["text"]
        for result in retrieved_results
    )

    return context


# ============================================================
# LLM GENERATION
# ============================================================

def generate_review(prompt_text: str) -> str:
    """
    Send the complete review prompt to the Bedrock model.

    Returns the raw text generated by the LLM.
    """

    response = bedrock_client.converse(
        modelId=MODEL_ID,
        messages=[
            {
                "role": "user",
                "content": [
                    {
                        "text": prompt_text
                    }
                ],
            }
        ],
        inferenceConfig={
            "temperature": 0.0,
            "maxTokens": 5000,
        },
    )

    return response["output"]["message"]["content"][0]["text"]


# ============================================================
# JSON PARSING
# ============================================================

def parse_review(raw_review: str) -> dict:
    """
    Convert the LLM response from JSON text into a Python dictionary.

    A minimal fallback removes Markdown code fences if the model
    adds them despite the prompt instructions.
    """

    try:
        return json.loads(raw_review)

    except json.JSONDecodeError:
        cleaned_review = (
            raw_review
            .strip()
            .removeprefix("```json")
            .removeprefix("```")
            .removesuffix("```")
            .strip()
        )

        return json.loads(cleaned_review)


# ============================================================
# REVIEW ONE PROPOSAL
# ============================================================
def override_rule(
    review_data: dict,
    deterministic_result: dict,
) -> None:

    rule_id = deterministic_result["rule_id"]

    results = review_data.get("results", [])

    for index, result in enumerate(results):
        if result.get("rule_id") == rule_id:
            results[index] = deterministic_result
            return

    # Safety fallback if Nova did not return the rule.
    results.append(deterministic_result)

def review_proposal(
    proposal_text: str,
    normalized_proposal: dict,
    reference_rules: str,
    prompt_template: str,
) -> dict:
    """
    Review one proposal against the retrieved reference rules.

    Returns the structured review as a Python dictionary.
    """

    prompt = (
        prompt_template
        .replace("{{REFERENCE_RULES}}", reference_rules)
        .replace("{{PROPOSAL}}", proposal_text)
    )

    raw_review = generate_review(prompt)

    review_data = parse_review(raw_review)

    deterministic_results = [
        check_rule_10(normalized_proposal),
        check_rule_13(normalized_proposal),
        check_rule_19(normalized_proposal),
        check_rule_20(normalized_proposal),
        check_rule_23(normalized_proposal),
        check_rule_25(normalized_proposal),
    ]

    for deterministic_rule in deterministic_results:
        override_rule(
            review_data,
            deterministic_rule,
        )

    return review_data


# ============================================================
# PROCESS ALL TEST PROPOSALS
# ============================================================

def process_proposals() -> None:
    """
    Review every proposal_*.txt file from the test directory
    and save one JSON review per proposal.
    """

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Load the prompt template once.
    prompt_template = PROMPT_PATH.read_text(
        encoding="utf-8"
    )

    RULES_PATH = Path(
    "data/knowledge_base/proposal_review_rules_v0.txt"
    )

    print("Loading mandatory reference rules...")

    reference_rules = RULES_PATH.read_text(
        encoding="utf-8"
    )

    rule_numbers = sorted(
        set(re.findall(r"RULE_?(\d{2})", reference_rules))
    )

    print(f"Mandatory rules loaded: {len(rule_numbers)}/31")

    # Find all test proposals.
    proposal_files = sorted(
        list(INPUT_DIR.glob("*.txt")) +
        list(INPUT_DIR.glob("*.pdf"))
    )

    if not proposal_files:
        print(
            f"No proposal files found in {INPUT_DIR}"
        )
        return

    print(
        f"{len(proposal_files)} proposal(s) found."
    )

    # Review every proposal.
    for file_path in proposal_files:

        print(
            f"\n--- Reviewing {file_path.name} ---"
        )

        proposal_text = load_proposal(file_path)
        normalized_proposal = normalize_document(proposal_text)

        try:
            review_data = review_proposal(
                proposal_text=proposal_text,
                normalized_proposal=normalized_proposal,
                reference_rules=reference_rules,
                prompt_template=prompt_template,
            )

        except json.JSONDecodeError:
            print(
                "ERROR: The model did not return valid JSON."
            )
            continue

        # Count detected violations.
        results = review_data.get(
            "results",
            []
        )

        violations = [
            result
            for result in results
            if result.get("status") == "NON_COMPLIANT"
        ]

        print(
            f"{len(violations)} non-compliance(s) detected."
        )

        # Save the structured review.
        output_file = (
            OUTPUT_DIR
            / f"{file_path.stem}_{file_path.suffix[1:]}_review.json"
        )

        with output_file.open(
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                review_data,
                file,
                indent=2,
                ensure_ascii=False,
            )

        print(
            f"Saved: {output_file}"
        )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    process_proposals()