import json
from pathlib import Path

import boto3


# ============================================================
# CONFIGURATION
# ============================================================

REGION = "us-east-1"
KNOWLEDGE_BASE_ID = "DJ33HADJNL"
MODEL_ID = "meta.llama3-8b-instruct-v1:0"

INPUT_DIR = Path("data/test_proposals")
OUTPUT_DIR = Path("data/results")
PROMPT_PATH = Path("prompts/reviewer_prompt.txt")


# ============================================================
# AWS CLIENTS
# ============================================================

kb_client = boto3.client(
    "bedrock-agent-runtime",
    region_name=REGION,
)

bedrock_client = boto3.client(
    "bedrock-runtime",
    region_name=REGION,
)


# ============================================================
# RETRIEVAL
# ============================================================

def retrieve_rules(query: str) -> str:
    """
    Retrieve relevant quality rules from the Bedrock Knowledge Base.

    Returns the retrieved chunks combined into a single text context.
    """

    response = kb_client.retrieve(
        knowledgeBaseId=KNOWLEDGE_BASE_ID,
        retrievalQuery={
            "text": query
        },
        retrievalConfiguration={
            "managedSearchConfiguration": {
                "numberOfResults": 5
            }
        },
    )

    retrieved_results = response["retrievalResults"]

    context = "\n\n".join(
        result["content"]["text"]
        for result in retrieved_results
    )

    return context


# ============================================================
# LLM GENERATION
# ============================================================

def generate_review(prompt_text: str) -> str:
    """
    Send the complete review prompt to the Bedrock model.

    Returns the raw text generated by the LLM.
    """

    response = bedrock_client.converse(
        modelId=MODEL_ID,
        messages=[
            {
                "role": "user",
                "content": [
                    {
                        "text": prompt_text
                    }
                ],
            }
        ],
        inferenceConfig={
            "temperature": 0.0,
            "maxTokens": 1500,
        },
    )

    return response["output"]["message"]["content"][0]["text"]


# ============================================================
# JSON PARSING
# ============================================================

def parse_review(raw_review: str) -> dict:
    """
    Convert the LLM response from JSON text into a Python dictionary.

    A minimal fallback removes Markdown code fences if the model
    adds them despite the prompt instructions.
    """

    try:
        return json.loads(raw_review)

    except json.JSONDecodeError:
        cleaned_review = (
            raw_review
            .strip()
            .removeprefix("```json")
            .removeprefix("```")
            .removesuffix("```")
            .strip()
        )

        return json.loads(cleaned_review)


# ============================================================
# REVIEW ONE PROPOSAL
# ============================================================

def review_proposal(
    proposal_text: str,
    reference_rules: str,
    prompt_template: str,
) -> dict:
    """
    Review one proposal against the retrieved reference rules.

    Returns the structured review as a Python dictionary.
    """

    prompt = (
        prompt_template
        .replace("{{REFERENCE_RULES}}", reference_rules)
        .replace("{{PROPOSAL}}", proposal_text)
    )

    raw_review = generate_review(prompt)

    review_data = parse_review(raw_review)

    return review_data


# ============================================================
# PROCESS ALL TEST PROPOSALS
# ============================================================

def process_proposals() -> None:
    """
    Review every proposal_*.txt file from the test directory
    and save one JSON review per proposal.
    """

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Load the prompt template once.
    prompt_template = PROMPT_PATH.read_text(
        encoding="utf-8"
    )

    # Retrieve the reference rules once.
    #
    # We use the same reference context for all proposals,
    # so there is no reason to repeat this retrieval for every file.
    rules_query = (
        "Retrieve the quality rules that should be used "
        "to review a software development proposal."
    )

    print("Retrieving reference rules...")

    reference_rules = retrieve_rules(
        rules_query
    )

    # Find all test proposals.
    proposal_files = sorted(
        INPUT_DIR.glob("proposal_*.txt")
    )

    if not proposal_files:
        print(
            f"No proposal files found in {INPUT_DIR}"
        )
        return

    print(
        f"{len(proposal_files)} proposal(s) found."
    )

    # Review every proposal.
    for file_path in proposal_files:

        print(
            f"\n--- Reviewing {file_path.name} ---"
        )

        proposal_text = file_path.read_text(
            encoding="utf-8"
        )

        try:
            review_data = review_proposal(
                proposal_text=proposal_text,
                reference_rules=reference_rules,
                prompt_template=prompt_template,
            )

        except json.JSONDecodeError:
            print(
                "ERROR: The model did not return valid JSON."
            )
            continue

        # Count detected violations.
        results = review_data.get(
            "results",
            []
        )

        violations = [
            result
            for result in results
            if result.get("status") == "NON_COMPLIANT"
        ]

        print(
            f"{len(violations)} non-compliance(s) detected."
        )

        # Save the structured review.
        output_file = (
            OUTPUT_DIR
            / f"{file_path.stem}_review.json"
        )

        with output_file.open(
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                review_data,
                file,
                indent=2,
                ensure_ascii=False,
            )

        print(
            f"Saved: {output_file}"
        )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    process_proposals()